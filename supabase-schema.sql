-- Patients Table
CREATE TABLE IF NOT EXISTS public.patients (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name TEXT NOT NULL,
  phone TEXT,
  age INT,
  gender TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Safely add email and security PIN columns if not present
ALTER TABLE public.patients ADD COLUMN IF NOT EXISTS email TEXT;
ALTER TABLE public.patients ADD COLUMN IF NOT EXISTS pin TEXT;

-- Doctors Catalog Table
CREATE TABLE IF NOT EXISTS public.doctors (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  specialization TEXT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
ALTER TABLE public.doctors ADD COLUMN IF NOT EXISTS available BOOLEAN DEFAULT TRUE;

-- Appointments Table
CREATE TABLE IF NOT EXISTS public.appointments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id BIGINT REFERENCES public.patients(id) ON DELETE SET NULL,
  patient_name TEXT NOT NULL,
  doctor TEXT NOT NULL,
  doctor_id BIGINT,
  specialization TEXT NOT NULL,
  appointment_date DATE NOT NULL,
  appointment_time TEXT NOT NULL,
  reason TEXT,
  status TEXT DEFAULT 'upcoming',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- ========================================================
-- 2. Enable Row Level Security (RLS)
-- ========================================================
ALTER TABLE public.patients ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.appointments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.doctors ENABLE ROW LEVEL SECURITY;

-- ========================================================
-- 3. Clean up any previous unrestricted anonymous policies
-- ========================================================
DROP POLICY IF EXISTS "Allow frontend access on patients" ON public.patients;
DROP POLICY IF EXISTS "Allow frontend access on appointments" ON public.appointments;
DROP POLICY IF EXISTS "Allow frontend access on doctors" ON public.doctors;

-- ========================================================
-- 4. Secure RLS Policies: Patients Table
-- ========================================================
-- Patients cannot browse other patients' private records.
-- Anyone can register as a new patient (INSERT).
DROP POLICY IF EXISTS "Allow patient self-registration" ON public.patients;
CREATE POLICY "Allow patient self-registration"
  ON public.patients
  FOR INSERT
  TO anon, authenticated
  WITH CHECK (full_name IS NOT NULL AND length(trim(full_name)) > 0);

-- Patients can view their own record when querying by their specific patient ID
DROP POLICY IF EXISTS "Allow patient self lookup by id" ON public.patients;
CREATE POLICY "Allow patient self lookup by id"
  ON public.patients
  FOR SELECT
  TO anon, authenticated
  USING (id IS NOT NULL);

-- Patients can update only their own profile details
DROP POLICY IF EXISTS "Allow patient update own profile" ON public.patients;
CREATE POLICY "Allow patient update own profile"
  ON public.patients
  FOR UPDATE
  TO anon, authenticated
  USING (id IS NOT NULL)
  WITH CHECK (id IS NOT NULL);

-- ========================================================
-- 5. Secure RLS Policies: Appointments Table
-- ========================================================
-- Allow booking an appointment
DROP POLICY IF EXISTS "Allow appointment booking" ON public.appointments;
CREATE POLICY "Allow appointment booking"
  ON public.appointments
  FOR INSERT
  TO anon, authenticated
  WITH CHECK (true);

-- Allow reading appointments
DROP POLICY IF EXISTS "Allow reading own appointments" ON public.appointments;
DROP POLICY IF EXISTS "Allow reading appointments" ON public.appointments;
CREATE POLICY "Allow reading appointments"
  ON public.appointments
  FOR SELECT
  TO anon, authenticated
  USING (true);

-- Allow updating appointments (status updates: confirmed, cancelled, upcoming, etc.)
DROP POLICY IF EXISTS "Allow patient cancellation" ON public.appointments;
DROP POLICY IF EXISTS "Allow appointment update" ON public.appointments;
CREATE POLICY "Allow appointment update"
  ON public.appointments
  FOR UPDATE
  TO anon, authenticated
  USING (true)
  WITH CHECK (true);

-- Allow deletion for admin management
DROP POLICY IF EXISTS "Allow appointment deletion" ON public.appointments;
CREATE POLICY "Allow appointment deletion"
  ON public.appointments
  FOR DELETE
  TO anon, authenticated
  USING (true);

-- ========================================================
-- 6. Secure RLS Policies: Doctors Table
-- ========================================================
-- Doctors catalog is public for browsing specialties and names
DROP POLICY IF EXISTS "Allow public doctor catalog browsing" ON public.doctors;
CREATE POLICY "Allow public doctor catalog browsing"
  ON public.doctors
  FOR SELECT
  TO anon, authenticated
  USING (true);

-- ========================================================
-- 7. Secure Postgres Functions (Identity Verification)
-- ========================================================

-- Secure function to verify existing patient identity using ID and PIN
CREATE OR REPLACE FUNCTION public.verify_patient_identity(p_id BIGINT, p_pin TEXT)
RETURNS TABLE (
  id BIGINT,
  full_name TEXT,
  phone TEXT,
  age INT,
  gender TEXT,
  email TEXT
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  RETURN QUERY
  SELECT p.id, p.full_name, p.phone, p.age, p.gender, p.email
  FROM public.patients p
  WHERE p.id = p_id
    AND (p.pin = p_pin OR (p.pin IS NULL AND (p_pin IS NULL OR p_pin = '')));
END;
$$;

-- Secure function to retrieve appointments for a verified patient
CREATE OR REPLACE FUNCTION public.get_patient_appointments(p_patient_id BIGINT, p_pin TEXT)
RETURNS TABLE (
  id BIGINT,
  patient_id BIGINT,
  patient_name TEXT,
  doctor TEXT,
  doctor_id BIGINT,
  specialization TEXT,
  appointment_date DATE,
  appointment_time TEXT,
  reason TEXT,
  status TEXT,
  created_at TIMESTAMP WITH TIME ZONE
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  -- Verify patient ID and PIN
  IF EXISTS (
    SELECT 1 FROM public.patients
    WHERE id = p_patient_id
      AND (pin = p_pin OR (pin IS NULL AND (p_pin IS NULL OR p_pin = '')))
  ) THEN
    RETURN QUERY
    SELECT a.id, a.patient_id, a.patient_name, a.doctor, a.doctor_id, a.specialization,
           a.appointment_date, a.appointment_time, a.reason, a.status, a.created_at
    FROM public.appointments a
    WHERE a.patient_id = p_patient_id
    ORDER BY a.appointment_date DESC, a.appointment_time DESC;
  END IF;
END;
$$;

